# ---------------------------------------------------------------- sound effects
SR = 48000
rng = np.random.default_rng(3)
def tt(d): return np.arange(int(d*SR)) / SR
def lowpass(x, cut):
    y = np.zeros_like(x); a = 1 - np.exp(-2*np.pi*np.asarray(cut)/SR) * np.ones_like(x); acc = 0.0
    for i in range(len(x)): acc += a[i]*(x[i]-acc); y[i] = acc
    return y
def stereo(m, pan=None):
    if pan is None: return np.stack([m, m], 1)
    return np.stack([m*np.sqrt(1-pan), m*np.sqrt(pan)], 1)

def sfx_whoosh():
    t = tt(0.75); env = np.sin(np.pi*t/t[-1])**2
    cut = 300 + 3800*np.sin(np.pi*t/t[-1])**3
    m = lowpass(rng.standard_normal(len(t)), cut) * env
    return stereo(m/np.abs(m).max()*0.6, np.clip(t/t[-1], 0.05, 0.95))
def sfx_pop():
    t = tt(0.16); f = 1300*np.exp(-t*28) + 380
    m = np.sin(2*np.pi*np.cumsum(f)/SR) * np.exp(-t*32)
    return stereo(m*0.5)
def sfx_impact():
    t = tt(1.8); f = 70*np.exp(-t*1.5) + 38
    sub = np.sin(2*np.pi*np.cumsum(f)/SR) * np.exp(-t*2.6)
    noise = lowpass(rng.standard_normal(len(t)), 900*np.ones(len(t))) * np.exp(-t*14) * 2.2
    m = np.tanh((sub + noise)*1.6)
    return stereo(m/np.abs(m).max()*0.9)
def sfx_riser():
    t = tt(1.7); f = 160*np.power(10, t/t[-1])
    tone = np.sin(2*np.pi*np.cumsum(f)/SR)*0.5 + np.sin(2*np.pi*np.cumsum(f*1.5)/SR)*0.25
    noise = lowpass(rng.standard_normal(len(t)), 400 + 5000*(t/t[-1])**2)
    env = (t/t[-1])**2.2; env[-int(0.04*SR):] *= np.linspace(1, 0, int(0.04*SR))
    m = (tone + noise*1.4)*env
    return stereo(m/np.abs(m).max()*0.6)
def sfx_shimmer():
    t = tt(2.2); m = np.zeros(len(t))
    for k in range(10):
        st = k*0.06; f = rng.uniform(2200, 6200)
        seg = t >= st; tt2 = t[seg]-st
        m[seg] += np.sin(2*np.pi*f*tt2) * np.exp(-tt2*3.2) * (0.6 if k % 2 else 1)
    d = int(0.11*SR); m[d:] += m[:-d]*0.35
    return stereo(m/np.abs(m).max()*0.35, 0.5 + 0.0*t)

def build_sfx():
    bank = {"whoosh": sfx_whoosh(), "pop": sfx_pop(), "impact": sfx_impact(), "riser": sfx_riser(), "shimmer": sfx_shimmer()}
    n = int(TOTAL*SR) + SR; track = np.zeros((n, 2))
    for t, name, g in sfx_events:
        clip = bank.get(name)
        if clip is None: continue
        i = int(t*SR); j = min(n, i + len(clip)); track[i:j] += clip[:j-i]*g
    track = np.clip(track*CFG.get("sfx_volume", 0.9), -1, 1)
    with wave.open(str(WORK / "sfx.wav"), "wb") as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((track*32767).astype("<i2").tobytes())

# ---------------------------------------------------------------- ffmpeg
def render():
    starts = [sc["start"] for sc in scenes if 0.5 < sc["start"] < TOTAL]
    pulse = "+".join(f"0.045*exp(-5*(t-{s:.2f}))*gte(t,{s:.2f})" for s in starts) or "0"
    S = f"(0.82+0.18*min(t/1.1,1))*(1+{pulse})"
    T = f"{TOTAL:.2f}"
    cmd = ["ffmpeg", "-y", "-hide_banner"]
    for img in ["bg.png", "rays.png", "glow.png", "card.png", "particles.png", "shade.png"]:
        cmd += ["-loop", "1", "-framerate", str(FPS), "-t", T, "-i", str(WORK / img)]
    cmd += ["-i", str(VOICE), "-i", str(WORK / "sfx.wav")]
    if MUSIC: cmd += ["-stream_loop", "-1", "-i", str(MUSIC)]
    fonts = ROOT / "fonts"
    fontsdir = ":fontsdir=fonts" if fonts.exists() and any(fonts.glob("*.[ot]tf")) else ""
