#!/usr/bin/env python3
"""
Motion graphics video renderer (GitHub Actions friendly).
Input : input/product.(jpg|png), input/voiceover.mp3, input/subtitles.srt,
        optional input/music.mp3 (background music), config.json
Output: output/<output_name>.mp4  (1080x1920 vertical, Facebook Reels ready)

Everything (graphics, vector ornaments, sound effects) is generated by code.
No emoji is used anywhere.
"""
